class LockTests(ScratchTestCase):
    """Lock parsing and checks."""

    def test_parse_lock_reads_hashed_pins(self):
        """Hashed pins, multiple hashes, markers and comments are accepted."""
        text = synthetic_lock({"FastAPI": "9.1.0"}, hashes=3) + (
            "\n# comment\n"
            "colorama==9.2.0 ; sys_platform == 'win32' \\\n"
            "\t--hash=sha256:" + "Ab" * 32 + "\n")
        pins, problems = check.parse_lock(text)
        self.assertEqual(problems, [])
        self.assertEqual(pins, {"fastapi": "9.1.0", "colorama": "9.2.0"})

    def assert_one_problem(self, text, fragment):
        """Assert parse_lock reports exactly one problem naming fragment."""
        _, problems = check.parse_lock(text)
        self.assertEqual(len(problems), 1, problems)
        self.assertIn(fragment, problems[0])

    def test_unpinned_line_is_reported(self):
        """A range requirement is not an exact lock pin."""
        pins, problems = check.parse_lock("fastapi>=9.0\n")
        self.assertEqual(pins, {})
        self.assertEqual(len(problems), 1)

    def test_hashless_pin_is_rejected(self):
        """A marked pin followed by a comment, blank or pin has no hash."""
        for follower in ("    # via synthetic\n", "\n",
                         "pytest==9.2.0 \\\n    " + SYNTHETIC_HASH + "\n"):
            with self.subTest(follower=follower):
                self.assert_one_problem("fastapi==9.1.0 \\\n" + follower,
                                        "not followed by a valid hash")

    def test_pin_without_marker_is_rejected(self):
        """A pin lacking the continuation marker fails, hashes or not."""
        self.assert_one_problem("fastapi==9.1.0\n", "continuation marker")
        _, problems = check.parse_lock("fastapi==9.1.0\n    "
                                       + SYNTHETIC_HASH + "\n")
        self.assertEqual(len(problems), 2)
        self.assertIn("continuation marker", problems[0])
        self.assertIn("orphan hash", problems[1])

    def test_malformed_hash_is_rejected(self):
        """Wrong algorithm, length, characters or indentation fail."""
        for bad in ("    --hash=md5:" + "0" * 32,
                    "    --hash=sha256:" + "0" * 63,
                    "    --hash=sha256:" + "g" * 64,
                    "    --hash=sha256:" + "0" * 64 + " extra",
                    SYNTHETIC_HASH):
            with self.subTest(bad=bad):
                _, problems = check.parse_lock(
                    "fastapi==9.1.0 \\\n" + bad + "\n")
                self.assertEqual(len(problems), 2, problems)
                self.assertIn("not followed by a valid hash", problems[0])
                self.assertIn("malformed hash", problems[1])

    def test_orphan_hash_is_rejected(self):
        """A valid hash line outside a pin continuation fails."""
        self.assert_one_problem(
            synthetic_lock({"fastapi": "9.1.0"}) + "    " + SYNTHETIC_HASH
            + "\n", "orphan hash")
        self.assert_one_problem("    " + SYNTHETIC_HASH + "\n", "orphan hash")

    def test_unterminated_continuation_is_rejected(self):
        """A final hash line that still carries the marker fails."""
        self.assert_one_problem("fastapi==9.1.0 \\\n    " + SYNTHETIC_HASH
                                + " \\\n", "lock ends inside")

    def test_directives_are_rejected(self):
        """Index, find-links, install and build directives are refused."""
        directives = ("--index-url https://example.invalid/simple",
                      "--extra-index-url https://example.invalid/simple",
                      "-i https://example.invalid/simple",
                      "--find-links W:\\synthetic", "-f W:\\synthetic",
                      "--no-index", "--trusted-host example.invalid",
                      "--no-binary :all:", "--only-binary :all:",
                      "--prefer-binary", "--pre", "--require-hashes",
                      "--no-build-isolation",
                      "--config-settings key=value",
                      "-e W:\\synthetic", "-r other.txt", "-c other.txt")
        base = synthetic_lock(SYNTHETIC_PINS)
        for directive in directives:
            with self.subTest(directive=directive):
                pins, problems = check.parse_lock(base + directive + "\n")
                self.assertEqual(pins, SYNTHETIC_PINS)
                self.assertEqual(len(problems), 1, problems)
                self.assertIn("disallowed directive", problems[0])

    def test_missing_lock_is_pending(self):
        """A missing lock reports pending resolution."""
        pins, problems = check.lock_problems(
            os.path.join(self.scratch, "absent.lock.txt"))
        self.assertEqual(pins, {})
        self.assertIn("lock resolution pending", problems[0])

    def test_lock_with_excluded_and_missing_packages_fails(self):
        """Excluded packages and missing required pins are reported."""
        pins = dict(SYNTHETIC_PINS)
        del pins["clearml"]
        pins["torch"] = "9.9.0"
        path = self.write("app.lock.txt", synthetic_lock(pins))
        _, problems = check.lock_problems(path)
        self.assertIn("lock does not pin clearml", problems)
        self.assertIn("lock contains excluded package torch", problems)

    def test_complete_lock_passes(self):
        """A lock pinning every required package passes."""
        path = self.write("app.lock.txt", synthetic_lock(SYNTHETIC_PINS))
        pins, problems = check.lock_problems(path)
        self.assertEqual(problems, [])
        self.assertEqual(pins, SYNTHETIC_PINS)


class EnvironmentTests(ScratchTestCase):
    """pyvenv.cfg and configured-path checks."""

    def make_environment(self, pyvenv):
        """Create a synthetic environment layout and return its root."""
        os.makedirs(os.path.join(self.scratch, "Scripts"))
        self.write(os.path.join("Scripts", "python.exe"), "")
        self.write("pyvenv.cfg", pyvenv)
        return self.scratch

    def test_configured_directories_use_the_runtime_root(self):
        """The environment and temp destinations resolve in the runtime root."""
        for key in ("uv_project_env", "temp"):
            path, root = check.configured_directory(key)
            self.assertEqual(root, guard.RUNTIME_ROOT)
            self.assertTrue(guard.is_within(path, guard.RUNTIME_ROOT,
                                            strict=True))
            self.assertFalse(guard.is_within(path, guard.PRIVATE_ROOT))
            self.assertFalse(guard.is_within(path, guard.REPO_ROOT))

    def test_configured_directory_refuses_relaxed_roots(self):
        """A workspace-only key on the runtime root or a moved root is refused."""
        with open(PATHS_PATH, "r", encoding="utf-8") as handle:
            config = json.load(handle)
        for key, change in (
                ("outputs", lambda c: c["directories"]["outputs"].update(
                    root="runtime")),
                ("temp", lambda c: c.update(runtime_root="G:\\elsewhere")),
                ("temp", lambda c: c["directories"]["temp"].update(
                    root="other"))):
            variant = json.loads(json.dumps(config))
            change(variant)
            path = self.write("paths.json", json.dumps(variant))
            with self.assertRaises(check.CheckError, msg=key):
                check.configured_directory(key, path)

    def test_environment_on_the_wrong_root_is_refused(self):
        """The environment check uses the root it is given explicitly."""
        root = self.make_environment(
            "version_info = 3.12.8\ninclude-system-site-packages = false\n")
        problems = check.environment_problems(root, guard.PRIVATE_ROOT)
        self.assertIn("not inside", problems[0])

    def test_valid_environment_passes(self):
        """A 3.12.8 venv without system site-packages passes."""
        root = self.make_environment(
            "home = C:\\synthetic\nimplementation = CPython\n"
            "version_info = 3.12.8\ninclude-system-site-packages = false\n")
        self.assertEqual(check.environment_problems(root,
                                                    guard.RUNTIME_ROOT), [])

    def test_wrong_version_and_system_site_packages_fail(self):
        """A different Python or shared site-packages is reported."""
        root = self.make_environment(
            "version = 3.11.0\ninclude-system-site-packages = true\n")
        self.assertEqual(len(check.environment_problems(
            root, guard.RUNTIME_ROOT)), 2)

    def test_missing_environment_is_reported(self):
        """An absent interpreter reports that the environment is missing."""
        problems = check.environment_problems(
            os.path.join(self.scratch, "absent"), guard.RUNTIME_ROOT)
        self.assertIn("does not exist yet", problems[0])


class ProbeEnvironmentTests(unittest.TestCase):
    """Minimal child-process environment."""

    def test_credentials_are_dropped_and_caches_routed(self):
        """Credentials are not passed on; caches and ClearML are routed."""
        smoke = guard.RUNTIME_ROOT + "\\temp\\" + check.SMOKE_DIR_NAME
        environ = {"SYSTEMROOT": "C:\\Windows", "PATH": "C:\\elsewhere",
                   CLEARML_CREDENTIAL_NAME: "x", DB_CREDENTIAL_NAME: "x",
                   "PYTHONPATH": "C:\\elsewhere", "HOME": "C:\\elsewhere"}
        env = check.probe_environment(SYNTHETIC_ENV, smoke, environ)
        for name in (CLEARML_CREDENTIAL_NAME, DB_CREDENTIAL_NAME,
                     "PYTHONPATH"):
            self.assertNotIn(name, env)
        for name in check.ROUTED_VARIABLES:
            self.assertEqual(env[name], smoke)
        self.assertEqual(env["CLEARML_OFFLINE_MODE"], "1")
        self.assertEqual(env["CLEARML_CONFIG_FILE"],
                         smoke + "\\" + check.CLEARML_CONFIG_NAME)
        self.assertEqual(env["USERNAME"], check.SYNTHETIC_USERNAME)
        self.assertTrue(env["PATH"].startswith(SYNTHETIC_ENV + "\\Scripts;"))
        self.assertNotIn("elsewhere", env["PATH"])

    def test_probe_command_is_isolated(self):
        """The probe runs with -I -B and names no upstream code to import."""
        command = check.probe_command("python.exe", "W:\\synthetic-upstream")
        self.assertEqual(command[1:3], ["-I", "-B"])
        spec = json.loads(command[-1])
        self.assertEqual(spec["app_module"], check.APP_MODULE)
        self.assertIn("torch", spec["forbidden_modules"])
        self.assertIn("torch_geometric", spec["forbidden_modules"])


class ProbeResultTests(unittest.TestCase):
    """Evaluation of synthetic probe results."""

    def test_passing_result(self):
        """A complete, matching result has no problems."""
        self.assertEqual(check.probe_problems(probe_result(), SYNTHETIC_PINS,
                                              SYNTHETIC_ENV), [])

    def test_version_mismatch_and_forbidden_module_fail(self):
        """A lock mismatch, a loaded torch and an upstream path fail."""
        result = probe_result(forbidden_loaded=["torch"],
                              forbidden_installed=["torch"],
                              upstream_on_path=True)
        result["packages"]["fastapi"]["distribution_version"] = "0.0.1"
        problems = check.probe_problems(result, SYNTHETIC_PINS, SYNTHETIC_ENV)
        self.assertEqual(len(problems), 4)

    def test_wrong_environment_and_failed_app_import_fail(self):
        """Another prefix and a failed package import are reported."""
        result = probe_result(prefix="G:\\Industry Dataset\\other",
                              app={"import_status": "import_failed",
                                   "import_error_type": "ImportError"})
        problems = check.probe_problems(result, SYNTHETIC_PINS, SYNTHETIC_ENV)
        self.assertEqual(len(problems), 2)

    def test_parse_probe_output_requires_one_marked_line(self):
        """Exactly one marked JSON line is accepted."""
        line = (check.PROBE_MARKER + json.dumps({"python": "9"})).encode()
        self.assertEqual(check.parse_probe_output(b"noise\n" + line),
                         {"python": "9"})
        with self.assertRaises(check.CheckError):
            check.parse_probe_output(line + b"\n" + line)
        with self.assertRaises(check.CheckError):
            check.parse_probe_output(b"no result")


class ProbeMechanicsTests(ScratchTestCase):
    """Run the fixed probe source with synthetic names only."""

    def test_probe_source_runs_with_synthetic_names(self):
        """The probe imports a synthetic package and reports exclusions."""
        package = os.path.join(self.scratch, "src", "synthetic_app_pkg")
        os.makedirs(package)
        with open(os.path.join(package, "__init__.py"), "w",
                  encoding="utf-8") as handle:
            handle.write('__version__ = "9.0.0"\n')
        upstream = os.path.join(self.scratch, "synthetic-upstream")
        spec = json.dumps({
            "marker": check.PROBE_MARKER,
            "src": os.path.join(self.scratch, "src"),
            "app_module": "synthetic_app_pkg",
            "imports": [["synthetic-absent-distribution", "json"],
                        ["synthetic-other-distribution",
                         "synthetic_absent_module"]],
            "forbidden_modules": ["synthetic_forbidden_module", "json"],
            "upstream_root": upstream})
        completed = subprocess.run(
            [sys.executable, "-I", "-B", "-c", check.PROBE_SOURCE, spec],
            cwd=self.scratch, stdin=subprocess.DEVNULL,
            stdout=subprocess.PIPE, stderr=subprocess.DEVNULL, timeout=120,
            check=False)
        self.assertEqual(completed.returncode, 0)
        result = check.parse_probe_output(completed.stdout)
        self.assertEqual(result["isolated"], 1)
        self.assertEqual(result["app"], {"import_status": "imported",
                                         "version": "9.0.0",
                                         "from_source": True})
        self.assertEqual(result["packages"]["synthetic-absent-distribution"],
                         {"distribution_version": None,
                          "import_status": "imported"})
        self.assertEqual(
            result["packages"]["synthetic-other-distribution"]
            ["import_status"], "import_failed")
        self.assertEqual(result["forbidden_loaded"], ["json"])
        self.assertEqual(result["forbidden_installed"], ["json"])
        self.assertIs(result["upstream_on_path"], False)


class ApplicationPackageTests(unittest.TestCase):
    """The side-effect-free application import surface."""

    def test_package_imports_without_excluded_modules(self):
        """Importing the package loads no excluded or upstream module."""
        code = ("import sys; sys.path.insert(0, sys.argv[1]); "
                "import ehr_evidence_app as app; import json; "
                "print(json.dumps([app.__version__, sorted(m for m in "
                "sys.argv[2:] if m in sys.modules)]))")
        completed = subprocess.run(
            [sys.executable, "-I", "-B", "-c", code,
             os.path.join(REPO_ROOT, "src")] + list(check.FORBIDDEN_MODULES),
            stdin=subprocess.DEVNULL, stdout=subprocess.PIPE,
            stderr=subprocess.DEVNULL, timeout=120, check=False)
        self.assertEqual(completed.returncode, 0)
        self.assertEqual(json.loads(completed.stdout), ["0.3.0", []])


class RunTests(unittest.TestCase):
    """End-to-end run with every external step mocked."""

    def test_run_passes_and_fails_on_probe_problem(self):
        """run() returns 0 for a clean probe and 1 when it reports torch."""
        patches = [
            mock.patch.object(check, "lock_problems",
                              return_value=(SYNTHETIC_PINS, [])),
            mock.patch.object(check, "configured_directory",
                              side_effect=lambda key: (SYNTHETIC_ENV,
                                                       guard.RUNTIME_ROOT)),
            mock.patch.object(check, "environment_problems", return_value=[]),
            mock.patch.object(check, "prepare_smoke_dir",
                              return_value="G:\\synthetic-smoke"),
            mock.patch.object(check, "upstream_root",
                              return_value="W:\\synthetic-upstream"),
            mock.patch("builtins.print"),
        ]
        for patch in patches:
            patch.start()
            self.addCleanup(patch.stop)
        with mock.patch.object(check, "run_probe",
                               return_value=probe_result()):
            self.assertEqual(check.run(), 0)
        with mock.patch.object(check, "run_probe", return_value=probe_result(
                forbidden_loaded=["torch"])):
            self.assertEqual(check.run(), 1)

    def test_missing_environment_skips_probe(self):
        """No probe runs when the environment layout check fails."""
        with mock.patch.object(check, "environment_problems",
                               return_value=["missing"]), \
                mock.patch.object(check, "run_probe") as probe, \
                mock.patch("builtins.print"):
            self.assertEqual(check.run(), 1)
        probe.assert_not_called()


