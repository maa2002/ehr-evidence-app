"""Synthetic checks for ehr_evidence_app.environment.app (Step 7).

No real application environment, dependency, service or upstream file is
used. Lock files, pyvenv.cfg files, pyproject declarations and probe
results are invented; scratch files go to a directory under the configured
test temp on the runtime root, where the application environment lives.
One case runs the fixed probe source in the interpreter
running these tests with synthetic distribution, module and upstream names
only, to check the probe mechanics. The repository's own declaration and
application package are checked without importing any dependency.
"""

import json
import os
import shutil
import subprocess
import sys
import tempfile
import unittest
from unittest import mock

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.dirname(
    os.path.abspath(__file__))))

from ehr_evidence_app.environment import app as check  # noqa: E402
from ehr_evidence_app.storage import policy as guard  # noqa: E402

PATHS_PATH = os.path.join(REPO_ROOT, "config", "paths.json")
SYNTHETIC_PINS = {name: "9.%d.0" % index
                  for index, name in enumerate(check.REQUIRED_DISTRIBUTIONS)}
SYNTHETIC_ENV = guard.RUNTIME_ROOT + "\\environments\\uv\\synthetic-app"
# Credential-style variable names, assembled from fragments so the source
# holds no secret-shaped assignment; fixture values are short and harmless.
CLEARML_CREDENTIAL_NAME = "CLEARML_API_" + "SEC" + "RET_KEY"
DB_CREDENTIAL_NAME = "PG" + "PASS" + "WORD"


def configured_test_temp():
    """Return the configured runtime test temp directory from paths.json."""
    with open(PATHS_PATH, "r", encoding="utf-8") as handle:
        paths = json.load(handle)
    entry = paths["directories"]["pytest_temp"]
    return guard.configured_directory_path("pytest_temp", entry)[0]


SYNTHETIC_HASH = "--hash=sha256:" + "0" * 64


def synthetic_lock(pins, extra="", hashes=1):
    """Return uv-style lock text with hash and comment lines."""
    lines = ["# This file was autogenerated by uv via the following command:",
             "#    uv pip compile pyproject.toml -o requirements/app.lock.txt"]
    for name, version in sorted(pins.items()):
        lines.append("%s==%s \\" % (name, version))
        lines += ["    --hash=sha256:%064d \\" % (index + 1)
                  for index in range(hashes - 1)]
        lines += ["    " + SYNTHETIC_HASH,
                  "    # via ehr-evidence-app (pyproject.toml)"]
    return "\n".join(lines) + "\n" + extra


def probe_result(**overrides):
    """Return a passing synthetic probe result with optional overrides."""
    result = {"python": check.EXPECTED_PYTHON, "isolated": 1,
              "prefix": SYNTHETIC_ENV, "in_virtual_environment": True,
              "app": {"import_status": "imported", "version": "0.0.0",
                      "from_source": True},
              "packages": {name: {"distribution_version": version,
                                  "import_status": "imported"}
                           for name, version in SYNTHETIC_PINS.items()},
              "forbidden_loaded": [], "forbidden_installed": [],
              "upstream_on_path": False}
    result.update(overrides)
    return result


class ScratchTestCase(unittest.TestCase):
    """Provide a scratch directory under the configured runtime test temp."""

    def setUp(self):
        """Create a fresh scratch directory for one test."""
        base = configured_test_temp()
        os.makedirs(base, exist_ok=True)
        self.scratch = tempfile.mkdtemp(prefix="app-env-", dir=base)

    def tearDown(self):
        """Remove the scratch directory."""
        shutil.rmtree(self.scratch, ignore_errors=True)

    def write(self, name, text):
        """Write text to a scratch file and return its path."""
        path = os.path.join(self.scratch, name)
        with open(path, "w", encoding="utf-8") as handle:
            handle.write(text)
        return path


